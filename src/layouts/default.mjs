import { renderSiteHeader } from "../components/site-header.mjs";
import { escapeAttribute, indent } from "../lib/html.mjs";
import { site } from "../site.mjs";

const analyticsTag = `<!-- Google tag (gtag.js) -->
<script async src="https://www.googletagmanager.com/gtag/js?id=G-6HQ3HT02XW"></script>
<script>
  window.dataLayer = window.dataLayer || [];
  function gtag(){dataLayer.push(arguments);}
  gtag('js', new Date());
  gtag('config', 'G-6HQ3HT02XW');
</script>`;

const themeBootstrap = `<script>
  document.documentElement.classList.add("js");
  try {
    const savedTheme = localStorage.getItem("theme");
    const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
    if (savedTheme === "dark" || (!savedTheme && prefersDark)) {
      document.documentElement.dataset.theme = "dark";
    }
  } catch (_) {}
</script>`;

export const renderPage = ({
  path,
  title,
  description,
  structuredData,
  indexable = true,
  mainClass = "page-shell",
  content,
}) => {
  const canonicalUrl = new URL(path, `${site.url}/`).href;
  const descriptionTags = description
    ? `<meta name="description" content="${escapeAttribute(description)}">
<meta property="og:description" content="${escapeAttribute(description)}">
<meta name="twitter:description" content="${escapeAttribute(description)}">`
    : "";
  const structuredDataTag = structuredData
    ? `<script type="application/ld+json">${JSON.stringify(structuredData).replaceAll("<", "\\u003c")}</script>`
    : "";

  return `<!doctype html>
<!-- Generated by scripts/build.mjs. Edit files in src/ instead. -->
<html lang="en">
  <head>
    <meta charset="utf-8">
${indent(analyticsTag, 4)}
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="color-scheme" content="light dark">
    <meta name="author" content="${escapeAttribute(site.name)}">
${descriptionTags ? `${indent(descriptionTags, 4)}\n` : ""}${indexable ? "" : "    <meta name=\"robots\" content=\"noindex,follow\">\n"}    <link rel="canonical" href="${escapeAttribute(canonicalUrl)}">
    <meta property="og:type" content="website">
    <meta property="og:site_name" content="${escapeAttribute(site.name)}">
    <meta property="og:title" content="${escapeAttribute(title)}">
    <meta property="og:url" content="${escapeAttribute(canonicalUrl)}">
    <meta name="twitter:card" content="summary">
    <meta name="twitter:title" content="${escapeAttribute(title)}">
    <title>${escapeAttribute(title)}</title>
${structuredDataTag ? `${indent(structuredDataTag, 4)}\n` : ""}${indent(themeBootstrap, 4)}
    <link rel="stylesheet" href="${site.stylesheet}">
    <script src="${site.script}" defer></script>
  </head>
  <body>
    <a class="skip-link" href="#content">Skip to content</a>

${indent(renderSiteHeader(path), 4)}

    <main id="content" class="${escapeAttribute(mainClass)}">
${indent(content, 6)}
    </main>
  </body>
</html>
`;
};
