import { renderSiteHeader } from "../components/site-header.mjs";
import { escapeAttribute, indent } from "../lib/html.mjs";
import { site } from "../site.mjs";

const themeBootstrap = `<script>
  document.documentElement.classList.add("js");
  try {
    const savedTheme = localStorage.getItem("theme");
    const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
    if (savedTheme === "dark" || (!savedTheme && prefersDark)) {
      document.documentElement.dataset.theme = "dark";
    }
  } catch (_) {}
</script>`;

export const renderPage = ({
  path,
  title,
  description,
  mainClass = "page-shell",
  content,
}) => {
  const descriptionTags = description
    ? `<meta name="description" content="${escapeAttribute(description)}">
<meta property="og:description" content="${escapeAttribute(description)}">`
    : "";

  return `<!doctype html>
<!-- Generated by scripts/build.mjs. Edit files in src/ instead. -->
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="color-scheme" content="light dark">
${descriptionTags ? `${indent(descriptionTags, 4)}\n` : ""}    <meta property="og:type" content="website">
    <meta property="og:title" content="${escapeAttribute(title)}">
    <title>${escapeAttribute(title)}</title>
${indent(themeBootstrap, 4)}
    <link rel="stylesheet" href="${site.stylesheet}">
    <script src="${site.script}" defer></script>
  </head>
  <body>
    <a class="skip-link" href="#content">Skip to content</a>

${indent(renderSiteHeader(path), 4)}

    <main id="content" class="${escapeAttribute(mainClass)}">
${indent(content, 6)}
    </main>
  </body>
</html>
`;
};
